// Package webui содержит интерфейс, общий для окна и для веба.
//
// Один и тот же файл на оба варианта намеренно: интерфейсы, написанные
// порознь, расходятся молча, и расходятся они прежде всего там, где
// подтверждение перед необратимым действием в одном оказывается слабее,
// чем в другом.
//
// Разница между вариантами сводится к двум вещам, и обе решаются внутри
// самой страницы: как вызывать методы ядра (мост Wails или запрос к
// серверу) и как получать события (шина Wails или поток SSE).
package webui

import (
	"embed"
	"io/fs"
)

//go:embed dist
var files embed.FS

// Assets отдаёт готовые файлы интерфейса.
func Assets() embed.FS { return files }

// Dist отдаёт содержимое каталога dist как файловую систему -
// в таком виде его ждёт обычный HTTP-сервер.
func Dist() fs.FS {
	sub, err := fs.Sub(files, "dist")
	if err != nil {
		// Невозможно при собранном пакете: каталог вшит в бинарь.
		panic("autobak: интерфейс не встроен: " + err.Error())
	}
	return sub
}
