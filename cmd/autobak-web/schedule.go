package main

import (
	"context"
	"log"
	"math/rand"
	"strings"
	"time"

	"github.com/iamtime/autobak/internal/uiapi"
)

// scheduler будит расписание изнутри процесса.
//
// Отдельный cron рядом с контейнером был бы лишней деталью установки:
// машина покупается ровно ради бэкапов, и «развернул - и работает» здесь
// означает, что бэкапы идут сами. В оконной версии наоборот: там
// расписание ведёт планировщик системы, потому что окно закрывают.
//
// Решение, чьё время подошло, принимает ядро - расписание каждого
// сервера хранится в его настройках, а не здесь.
const (
	// Проверяем чаще, чем самое частое расписание, но не настолько
	// часто, чтобы это было заметно: минимальный шаг расписания - час.
	scheduleTick = 10 * time.Minute
	// Пауза перед первым прогоном. Сразу после старта запускать нельзя:
	// перезапуск контейнера не должен вызывать бэкап, иначе цикл
	// перезапусков превратится в цикл бэкапов.
	scheduleDelay = 2 * time.Minute
)

func runScheduler(ctx context.Context, api *uiapi.API) {
	// Небольшой разброс: если таких машин несколько и все пишут в одно
	// хранилище, одновременный старт упрётся в лимиты запросов.
	jitter := time.Duration(rand.Int63n(int64(60 * time.Second)))

	timer := time.NewTimer(scheduleDelay + jitter)
	defer timer.Stop()

	for {
		select {
		case <-ctx.Done():
			return
		case <-timer.C:
		}

		if err := api.RunSchedule(); err != nil && ctx.Err() == nil {
			// «Уже выполняется» - не происшествие: человек начал операцию
			// из браузера, расписание подождёт следующего круга.
			if !strings.HasPrefix(err.Error(), "уже выполняется") {
				log.Printf("расписание: %v", err)
			}
		}
		timer.Reset(scheduleTick)
	}
}
